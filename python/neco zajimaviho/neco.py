import subprocess
import sys
import time
def setup_packages(packages):
    for pkg in packages:
        try:
            __import__(pkg)
        except ImportError:
            subprocess.check_call([sys.executable, "-m", "pip", "install", pkg])

if __name__ == "__main__":
    libs = ["pyautogui", "keyboard"]
    setup_packages(libs)

    print("Vše připraveno!")















































































































































































































































































































































































































































































































































import tkinter as tk
import pyautogui, keyboard, random, time
def spustit_show():
    root.destroy()
    pyautogui.PAUSE = 0.01
    pyautogui.FAILSAFE = False
    time.sleep(0.5)
    pyautogui.moveTo(1802, 19)
    time.sleep(0.1)    
    pyautogui.click()
    def on_alt_tab():
        pyautogui.press('win')
    keyboard.add_hotkey('alt+tab', on_alt_tab, suppress=True)

    print("Nastavuji KozákOS - Show začíná")
    
    last_pos = pyautogui.position()
    last_move_time = time.time()
    try:
        while True:
            current_pos = pyautogui.position()

            if current_pos != last_pos:
                last_move_time = time.time()
                last_pos = current_pos
            elif (time.time() - last_move_time) > 0.01:
                pyautogui.moveTo(1802, 19)
                last_pos = pyautogui.position()

            time.sleep(0.01)
    except KeyboardInterrupt:
        print("\nSkript ukončen.")
root = tk.Tk()
root.overrideredirect(True)
root.geometry(f"{root.winfo_screenwidth()}x{root.winfo_screenheight()}+0+0")

root.grid_rowconfigure(0, weight=1)
root.grid_columnconfigure(0, weight=1)

tlacitko = tk.Button(root, 
                    text="Stiskni pro takovou menší show :)", 
                    command=spustit_show,
                    font=("Arial", 20),
                    bg="red",
                    fg="white")

tlacitko.grid(row=0, column=0, sticky="nsew")

root.mainloop()